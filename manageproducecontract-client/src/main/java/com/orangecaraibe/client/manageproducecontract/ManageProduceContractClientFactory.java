package com.orangecaraibe.client.manageproducecontract;

import com.orangecaraibe.epco.manageproducecontract.ManageProduceContract;
import org.apache.cxf.endpoint.Client;
import org.apache.cxf.ext.logging.LoggingFeature;
import org.apache.cxf.frontend.ClientProxy;
import org.apache.cxf.jaxws.JaxWsProxyFactoryBean;
import org.apache.cxf.transport.http.HTTPConduit;
import org.apache.cxf.transports.http.configuration.HTTPClientPolicy;

import javax.xml.ws.BindingProvider;

/**
 * Builds a CXF 3.4 proxy for the ManageProduceContract SOAP service.
 * <p>
 * {@link ManageProduceContract} is the service endpoint interface generated by wsdl2java
 * from the {@code ns1:ManageProduceContract} portType.
 */
public final class ManageProduceContractClientFactory {

    public static final String DEFAULT_ADDRESS =
            "http://epco.gitg.ms.fcm/soa/manageProduceContract";

    private String address = DEFAULT_ADDRESS;
    private long connectTimeoutMs = 10_000;
    private long receiveTimeoutMs = 30_000;
    private boolean logMessages;
    private String username;
    private String password;

    public ManageProduceContractClientFactory address(String address) {
        this.address = address;
        return this;
    }

    public ManageProduceContractClientFactory connectTimeout(long millis) {
        this.connectTimeoutMs = millis;
        return this;
    }

    public ManageProduceContractClientFactory receiveTimeout(long millis) {
        this.receiveTimeoutMs = millis;
        return this;
    }

    /** Logs SOAP requests/responses (useful while integrating). */
    public ManageProduceContractClientFactory logMessages(boolean logMessages) {
        this.logMessages = logMessages;
        return this;
    }

    /** Optional HTTP Basic authentication. */
    public ManageProduceContractClientFactory basicAuth(String username, String password) {
        this.username = username;
        this.password = password;
        return this;
    }

    public ManageProduceContract create() {
        JaxWsProxyFactoryBean factory = new JaxWsProxyFactoryBean();
        factory.setServiceClass(ManageProduceContract.class);
        factory.setAddress(address);
        if (logMessages) {
            LoggingFeature logging = new LoggingFeature();
            logging.setPrettyLogging(true);
            factory.getFeatures().add(logging);
        }

        ManageProduceContract port = (ManageProduceContract) factory.create();

        Client client = ClientProxy.getClient(port);
        HTTPConduit conduit = (HTTPConduit) client.getConduit();
        HTTPClientPolicy policy = new HTTPClientPolicy();
        policy.setConnectionTimeout(connectTimeoutMs);
        policy.setReceiveTimeout(receiveTimeoutMs);
        policy.setAllowChunking(false);
        conduit.setClient(policy);

        if (username != null) {
            BindingProvider bp = (BindingProvider) port;
            bp.getRequestContext().put(BindingProvider.USERNAME_PROPERTY, username);
            bp.getRequestContext().put(BindingProvider.PASSWORD_PROPERTY, password);
        }
        return port;
    }
}
